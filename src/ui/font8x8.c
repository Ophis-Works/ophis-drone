/* g10: the 10x10 per-pixel scaled cache, built lazily once — UI thread only */
static unsigned char g10[96][10];
static int built;

const unsigned char *font_glyph10(unsigned char ch)
{
    if (!built) {
        for (int i = 0; i < 96; i++)
            for (int dy = 0; dy < 10; dy++) {
                unsigned char row = 0;
                for (int dx = 0; dx < 10; dx++)
                    if (glyph8x8[i][(dy * 8) / 10] & (1u << ((dx * 8) / 10)))
                        row |= (unsigned char)(1u << dx);
                g10[i][dy] = row;
            }
        built = 1;
    }
    if (ch < 0x20 || ch > 0x7F)
        return NULL;
    return g10[ch - 0x20];
}
